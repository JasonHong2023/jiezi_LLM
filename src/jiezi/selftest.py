"""芥子系統自我評測：從已收錄的資料用程式出題，量測「查資料＋回答」整套系統（使用者 2026-11-15 第 5 項）。
Jiezi self-test: questions generated by code from the bundled data, measuring the whole system (retrieval + answer).

- 不用 Claude 出題；固定亂數種子，資料版本又是鎖定的，所以每次題目相同。
- 判分只看模型自己寫的部分（gateway 附在 `---` 之後的原文不算，否則等於送分）；知識庫類只看有沒有查到對的文章。
- No Claude-written questions; fixed seed over pinned data, so the set is reproducible. Scoring looks only at the
  model's own text (never the appended source block); knowledge items check that the right article was retrieved."""

from __future__ import annotations

import json
import random
import re
import time
import urllib.request
from dataclasses import asdict, dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path

from .tools import evaluate

SEED = 20261116
PER_KIND = 10
WEEK = "一二三四五六日"


@dataclass
class Item:
    id: str
    kind: str
    question: str
    expect: list[str] = field(default_factory=list)  # 任一出現即對 / any one present counts
    number: float | None = None                      # 數值題：允許 0.5% 誤差 / numeric, 0.5% tolerance
    article: str | None = None                       # 知識庫：應查到的文章 / article that should be retrieved


# ── 出題 / Generators ──
def _calc(rng: random.Random) -> list[Item]:
    out = []
    for i in range(PER_KIND):
        a, b, c = rng.randint(12, 99), rng.randint(2, 30), rng.randint(3, 60)
        op1, op2 = rng.choice("+-*"), rng.choice("+-")
        expr = f"{a}{op1}{b}{op2}{c}"
        v = evaluate(expr)  # 同一個安全計算器，不用 eval / the same safe evaluator, no eval
        out.append(Item(f"calc-{i}", "calc", f"{expr.replace('*', '×')} 等於多少？", number=float(v)))
    return out


def _units(rng: random.Random) -> list[Item]:
    pairs = [("台斤", "公斤", 0.6), ("公斤", "台斤", 1 / 0.6), ("坪", "平方公尺", 400 / 121), ("公里", "英里", 1 / 1.609344),
             ("英里", "公里", 1.609344), ("磅", "公斤", 0.45359237), ("英吋", "公分", 2.54), ("公頃", "坪", 1e4 * 121 / 400)]
    out = []
    for i in range(PER_KIND):
        a, b, f = rng.choice(pairs)
        n = rng.randint(2, 50)
        out.append(Item(f"units-{i}", "units", f"{n} {a}是多少{b}？", number=n * f))
    return out


def _dates(rng: random.Random) -> list[Item]:
    out, start = [], date(2020, 1, 1)
    for i in range(PER_KIND):
        d = start + timedelta(days=rng.randint(0, 4000))
        w = WEEK[d.weekday()]
        out.append(Item(f"dates-{i}", "dates", f"{d.year}年{d.month}月{d.day}日是星期幾？",
                        expect=[f"星期{w}", f"週{w}", f"禮拜{w}"] + (["星期天", "禮拜天"] if w == "日" else [])))
    return out


def _dictionary(rng: random.Random, root: Path) -> list[Item]:
    from .dictionary import Dictionary, db_path
    try:
        d = Dictionary(db_path(root))
    except Exception:  # noqa: BLE001 - 沒建置就跳過 / skipped when not built
        return []
    out = []
    rows = d.con.execute("SELECT title, data FROM entries WHERE source = 'moedict-revised' AND length(title) = 4 "
                         "ORDER BY title").fetchall()
    for i, (title, data) in enumerate(rng.sample(rows, min(PER_KIND, len(rows)))):
        h = (json.loads(data).get("heteronyms") or [{}])[0]
        if h.get("bopomofo"):
            out.append(Item(f"zh-{i}", "dict-zh", f"「{title}」的注音是什麼？", expect=[h["bopomofo"]]))
    rows = d.con.execute("SELECT title, data FROM entries WHERE source = 'moedict-twblg' AND length(title) BETWEEN 2 AND 3 "
                         "ORDER BY title").fetchall()
    for i, (title, data) in enumerate(rng.sample(rows, min(PER_KIND, len(rows)))):
        h = (json.loads(data).get("heteronyms") or [{}])[0]
        if h.get("trs"):
            out.append(Item(f"tw-{i}", "dict-tw", f"台語的「{title}」台羅怎麼念？", expect=[h["trs"]]))
    return out


def _curriculum(rng: random.Random, root: Path) -> list[Item]:
    from .curriculum import Graph
    try:
        g = Graph.load(root)
    except Exception:  # noqa: BLE001
        return []
    out = []
    cands = sorted(t for t in g.topics if [p for p, s in g.prereq[t] if s == "hard"])
    for i, tid in enumerate(rng.sample(cands, min(PER_KIND, len(cands)))):
        t = g.topics[tid]
        pre = [g.topics[p]["name"] for p, s in g.prereq[tid] if s == "hard"]
        out.append(Item(f"cur-{i}", "curriculum", f"國小{t['subject']}的「{t['name']}」要先學會什麼？", expect=pre))
    books = [tb for tb in g.textbooks if tb["units"]]
    for i, tb in enumerate(rng.sample(books, min(PER_KIND, len(books)))):
        n = rng.randint(1, len(tb["units"]))
        out.append(Item(f"book-{i}", "textbook", f"{tb['level']}{tb['subject']} {tb['volume']} {tb['publisher']}的第 {n} 單元是什麼？",
                        expect=[tb["units"][n - 1][0]]))
    return out


def _knowledge(rng: random.Random, root: Path) -> list[Item]:
    from .knowledge import Knowledge, db_path
    try:
        k = Knowledge(db_path(root))
    except Exception:  # noqa: BLE001
        return []
    names = sorted(n for (n,) in k.con.execute("SELECT name FROM articles") if 2 <= len(n) <= 8 and "：" not in n)
    return [Item(f"kb-{i}", "knowledge", f"請簡單介紹「{n}」。", article=n)
            for i, n in enumerate(rng.sample(names, min(PER_KIND, len(names))))]


def _laws(rng: random.Random, root: Path) -> list[Item]:
    """「勞動基準法第 32 條規定什麼？」→ 回答要提到條文中的關鍵詞。 / Answers must mention a key phrase of the article."""
    from .laws import Laws, db_path
    try:
        lw = Laws(db_path(root))
    except Exception:  # noqa: BLE001
        return []
    famous = ["民法", "中華民國刑法", "勞動基準法", "個人資料保護法", "消費者保護法", "道路交通管理處罰條例",
              "著作權法", "公司法", "全民健康保險法", "中華民國憲法"]
    out = []
    for i in range(PER_KIND):
        name = rng.choice([n for n in famous if n in lw.by_name])
        rows = lw.con.execute("SELECT no, text FROM articles WHERE law = ? AND length(text) > 20 ORDER BY id",
                              (lw.by_name[name],)).fetchall()
        no, text = rng.choice(rows)
        words = [w for w in re.findall(r"[\u4e00-\u9fff]{4,}", text) if not w.startswith(("前項", "本法", "第"))]
        if words:
            out.append(Item(f"law-{i}", "laws", f"{name}{no.replace(' ', '')}規定什麼？", expect=words[:3]))
    return out


def build(root: Path) -> list[Item]:
    rng = random.Random(SEED)
    return (_calc(rng) + _units(rng) + _dates(rng) + _dictionary(rng, root) + _curriculum(rng, root)
            + _knowledge(rng, root) + _laws(rng, root))


# ── 判分 / Scoring ──
def model_text(content: str) -> str:
    """只取模型自己寫的部分（gateway 附錄之前）。 / The model's own text, before the gateway's appendix."""
    return (content or "").split("\n\n---\n", 1)[0]


def _norm(s: str) -> str:
    return re.sub(r"[\s　·‧,，。]", "", s or "").lower()


def score(item: Item, content: str, sources: list[dict]) -> bool:
    if item.article is not None:
        return any(s.get("article") == item.article for s in sources or [])
    text = model_text(content)
    if item.number is not None:
        nums = [float(x.replace(",", "")) for x in re.findall(r"-?\d[\d,]*(?:\.\d+)?", text)]
        tol = max(abs(item.number) * 0.005, 0.01)
        return any(abs(n - item.number) <= tol for n in nums)
    return any(_norm(e) in _norm(text) for e in item.expect if e)


# ── 執行 / Running ──
def ask(url: str, key: str, policy: str, question: str, timeout: float = 300) -> dict:
    req = urllib.request.Request(f"{url}/v1/chat/completions", method="POST",
                                 data=json.dumps({"model": policy, "messages": [{"role": "user", "content": question}]})
                                 .encode(), headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json",
                                          "X-Jiezi-Eval": "1"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def run(root: Path, url: str, key: str, policy: str = "jiezi-local", limit: int | None = None, log=print,
        ask_fn=ask) -> tuple[Path, dict]:
    items = build(root)
    if limit:
        items = [it for k in dict.fromkeys(i.kind for i in items) for it in [x for x in items if x.kind == k][:limit]]
    rows = []
    for n, it in enumerate(items, 1):
        t0 = time.monotonic()
        try:
            r = ask_fn(url, key, policy, it.question)
            content = (r.get("choices") or [{}])[0].get("message", {}).get("content") or ""
            meta = r.get("jiezi") or {}
            ok = score(it, content, meta.get("sources") or [])
            rows.append({**asdict(it), "ok": ok, "tier": meta.get("tier"), "answer": model_text(content)[:400],
                         "latency_s": round(time.monotonic() - t0, 2), "error": None})
        except Exception as exc:  # noqa: BLE001 - 單題失敗不中斷 / one failure never stops the run
            rows.append({**asdict(it), "ok": False, "tier": None, "answer": "", "latency_s": None,
                         "error": f"{type(exc).__name__}: {exc}"})
        if n % 10 == 0:
            log(f"  {n}/{len(items)}")
    by = {}
    for r in rows:
        k = by.setdefault(r["kind"], [0, 0])
        k[0] += r["ok"]
        k[1] += 1
    summary = {"policy": policy, "items": len(rows), "correct": sum(r["ok"] for r in rows),
               "errors": sum(1 for r in rows if r["error"]), "by_kind": {k: f"{c}/{n}" for k, (c, n) in by.items()}}
    out = root / "var" / "reports" / f"selftest-{datetime.now():%Y%m%d-%H%M}-{policy}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    md = [f"# 芥子自我評測 / Self-test（{policy}）", "", f"- 時間：{datetime.now().isoformat(timespec='seconds')}",
          f"- 題數 {summary['items']}，答對 {summary['correct']}，失敗 {summary['errors']}（種子 {SEED}）", "",
          "| 類別 / Kind | 答對 / Correct |", "|---|---|"] + [f"| {k} | {v} |" for k, v in summary["by_kind"].items()]
    md += ["", "## 答錯的題目 / Misses", "", "| 題目 | 期望 | 模型回答（前 80 字） |", "|---|---|---|"]
    for r in rows:
        if not r["ok"]:
            exp = r["article"] or r["number"] or "、".join(r["expect"][:3])
            ans = (r["error"] or r["answer"]).replace("|", "｜").replace("\n", " ")[:80]
            md.append(f"| {r['question']} | {exp} | {ans} |")
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    out.with_suffix(".jsonl").write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n",
                                         encoding="utf-8")
    return out, summary


def coverage(root: Path) -> dict:
    """不跑模型：只看 gateway 會不會附上含正確答案的資料（觸發與檢索的上限）。
    Without the model: does the gateway attach data that contains the answer? (an upper bound for triggers/retrieval)"""
    from . import tools
    parts = [lambda q: tools.grounding(q)]
    try:
        from .dictionary import Dictionary, db_path, grounding
        d = Dictionary(db_path(root))
        parts.append(lambda q: grounding(d, q))
    except Exception:  # noqa: BLE001
        pass
    try:
        from .curriculum import Graph, grounding as cg
        g = Graph.load(root)
        parts.append(lambda q: cg(g, q))
    except Exception:  # noqa: BLE001
        pass
    try:
        from .knowledge import Knowledge, db_path as kdb, grounding as kg
        k = Knowledge(kdb(root))
        parts.append(lambda q: kg(k, q))
    except Exception:  # noqa: BLE001
        pass
    try:
        from .laws import Laws, db_path as ldb, grounding as lg
        lw = Laws(ldb(root))
        parts.append(lambda q: lg(lw, q))
    except Exception:  # noqa: BLE001
        pass
    by, misses = {}, []
    for it in build(root):
        found = [r for r in (p(it.question) for p in parts) if r]
        text = "\n".join(r[0] for r in found)
        sources = [s for r in found for s in r[1]]
        ok = score(it, text, sources) if it.article is not None or it.number is None else \
            any(abs(float(x.replace(",", "")) - it.number) <= max(abs(it.number) * 0.005, 0.01)
                for x in re.findall(r"-?\d[\d,]*(?:\.\d+)?", text))
        c = by.setdefault(it.kind, [0, 0])
        c[0] += ok
        c[1] += 1
        if not ok:
            misses.append(it.question)
    return {"by_kind": {k: f"{a}/{n}" for k, (a, n) in by.items()}, "misses": misses}
