"""需要 sudo 的步驟：開新視窗、沒有時間限制地等待密碼（design D8；規則 R4、R15 C11）。
Steps that need sudo: open a new window and wait for the password with no time limit
(design D8; rules R4, R15 C11).

流程 / Flow:
  1. 主程式列出將執行的內容並取得同意（ask_consent）。
     The main process lists what will run and asks for consent (ask_consent).
  2. 產生包裝腳本：顯示說明 → 等使用者按 Enter → sudo -v，失敗就回到等待 →
     執行步驟腳本 → 把結束碼寫入狀態檔。
     Generate a wrapper: show the description → wait for Enter → sudo -v, back to waiting on
     failure → run the step script → write its exit code to a status file.
  3. 依平台開視窗執行；主程式等待狀態檔，沒有時間限制。
     Launch it in a window chosen by platform; the main process waits on the status file
     with no time limit."""

from __future__ import annotations

import os
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Callable

from .common import StepError, project_root

WRAPPER = """#!/usr/bin/env bash
# 由 jiezi_bootstrap 產生；執行完畢後可刪除 / Generated by jiezi_bootstrap; safe to delete afterwards
set -u
STATUS={status}
rm -f "$STATUS"
printf '\\n==== %s ====\\n\\n' {title}
cat {description}
echo
while true; do
  read -r -p "按 Enter 後輸入 sudo 密碼（不限時間） / Press Enter, then type the sudo password (no time limit): " _ || {{ echo 130 > "$STATUS"; exit 130; }}
  if sudo -v; then break; fi
  echo "sudo 驗證失敗，回到等待 / sudo authentication failed; waiting again"
done
# 長時間安裝期間保持 sudo 有效 / keep sudo alive during long installs
# 不佔用輸出管線，父程序結束時也一起結束 / detached from stdio; exits with the parent
PARENT=$$
( while kill -0 "$PARENT" 2>/dev/null; do sleep 30 & wait $!; sudo -n -v 2>/dev/null || exit; done ) </dev/null >/dev/null 2>&1 &
KEEPALIVE=$!
bash {step}
RC=$?
kill "$KEEPALIVE" 2>/dev/null
wait "$KEEPALIVE" 2>/dev/null
echo "$RC" > "$STATUS"
if [ "$RC" -eq 0 ]; then echo "完成 / Done"; else echo "失敗，結束碼 $RC / Failed with exit code $RC"; fi
read -r -p "按 Enter 關閉視窗 / Press Enter to close: " _ || true
"""


def detect_platform(env: dict | None = None, proc_version: Path = Path("/proc/version")) -> str:
    """回傳 'wsl2'、'ubuntu'（含其他原生 Linux）或 sys.platform。
    Return 'wsl2', 'ubuntu' (any native Linux), or sys.platform."""
    env = os.environ if env is None else env
    if not sys.platform.startswith("linux"):
        return sys.platform
    try:
        text = proc_version.read_text(errors="replace").lower()
    except OSError:
        text = ""
    if env.get("WSL_DISTRO_NAME") or "microsoft" in text:
        return "wsl2"
    return "ubuntu"


def choose_launcher(platform: str, env: dict, which: Callable[[str], str | None] = shutil.which,
                    title: str = "Jiezi setup") -> Callable[[str], list[str]] | None:
    """回傳「把包裝腳本路徑變成開窗指令」的函式；無法開窗時回傳 None（改在目前終端機執行）。
    Return a function mapping the wrapper path to a window-opening command, or None
    (run in the current terminal)."""
    if platform == "wsl2":
        distro = env.get("WSL_DISTRO_NAME")
        if not distro:
            return None
        inner = ["wsl.exe", "-d", distro, "--", "bash"]
        if which("wt.exe"):
            return lambda w: ["wt.exe", "-w", "new", "--title", title, *inner, w]
        if which("cmd.exe"):
            # cmd 的 start 把第一個參數當標題；用不含空白的標題避免引號問題
            # cmd's start takes the first argument as the title; avoid spaces to dodge quoting issues
            return lambda w: ["cmd.exe", "/c", "start", title.replace(" ", "-"), *inner, w]
        return None
    if platform == "ubuntu" and (env.get("DISPLAY") or env.get("WAYLAND_DISPLAY")):
        if which("x-terminal-emulator"):
            return lambda w: ["x-terminal-emulator", "-T", title, "-e", "bash", w]
        if which("gnome-terminal"):
            return lambda w: ["gnome-terminal", "--title", title, "--", "bash", w]
    return None


def write_wrapper(name: str, step_script: Path, description: str, title: str, workdir: Path) -> tuple[Path, Path]:
    """寫出包裝腳本與說明檔；回傳 (包裝腳本, 狀態檔)。
    Write the wrapper and description; return (wrapper, status file)."""
    workdir.mkdir(parents=True, exist_ok=True)
    desc = workdir / f"{name}.txt"
    desc.write_text(description.rstrip() + "\n", encoding="utf-8")
    status = workdir / f"{name}.status"
    wrapper = workdir / f"{name}.sh"
    q = shlex.quote
    wrapper.write_text(
        WRAPPER.format(status=q(str(status)), title=q(title), description=q(str(desc)), step=q(str(step_script))),
        encoding="utf-8",
    )
    wrapper.chmod(0o755)
    return wrapper, status


def ask_consent(description: str, inp: Callable[[str], str] = input, out=print) -> bool:
    """在目前終端機列出內容並詢問；非互動環境一律視為不同意。
    List the plan in the current terminal and ask; a non-interactive session counts as "no"."""
    out(description.rstrip())
    if not sys.stdin.isatty() and inp is input:
        out("非互動環境，不執行需要 sudo 的步驟 / Non-interactive session; sudo step not run")
        return False
    try:
        return inp("要執行嗎？ / Run it? [y/N] ").strip().lower() in {"y", "yes"}
    except EOFError:
        return False


def wait_for_status(status: Path, poll_s: float = 2.0, sleep=time.sleep) -> int:
    """等待狀態檔出現，沒有時間限制；回傳其中的結束碼。
    Wait for the status file with no time limit; return the exit code it holds."""
    while True:
        if status.exists():
            text = status.read_text().strip()
            if text:
                return int(text)
        sleep(poll_s)


def run_with_sudo(name: str, step_script: Path, description: str, title: str = "Jiezi setup",
                  root: Path | None = None, env: dict | None = None, log=print) -> int:
    """以新視窗（或目前終端機）執行需要 sudo 的步驟腳本，回傳其結束碼。
    呼叫前須先取得同意（ask_consent）。
    Run a sudo-requiring step script in a new window (or the current terminal) and return its
    exit code. Consent (ask_consent) must be obtained first."""
    env = dict(os.environ) if env is None else env
    root = root or project_root()
    wrapper, status = write_wrapper(name, step_script, description, title, root / "var" / "sudo")
    status.unlink(missing_ok=True)
    launcher = choose_launcher(detect_platform(env), env, title=title)
    if launcher is None:
        log("在目前終端機執行 / Running in the current terminal")
        rc = subprocess.run(["bash", str(wrapper)]).returncode
        text = status.read_text().strip() if status.exists() else ""
        return int(text) if text else (rc or 130)
    else:
        cmd = launcher(str(wrapper))
        log(f"已開新視窗等待輸入（不限時間） / Opened a new window; waiting with no time limit: {cmd[0]}")
        try:
            subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        except OSError as exc:
            raise StepError(f"cannot open a window with {cmd[0]}: {exc}") from exc
    return wait_for_status(status)
